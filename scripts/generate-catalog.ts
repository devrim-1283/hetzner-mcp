function pruneSchema(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(pruneSchema);
  if (!isRecord(node)) return node;

  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) {
    if (SCHEMA_MAP_KEYS.has(key)) {
      out[key] = pruneSchemaMap(value);
    } else if (NESTED_SCHEMA_KEYS.has(key)) {
      out[key] = pruneSchema(value);
    } else if (OPAQUE_SCHEMA_KEYS.has(key)) {
      out[key] = value;
    } else if (key === 'description') {
      if (typeof value === 'string') {
        const text = stripMarkdown(value);
        if (text.length > 0 && text.length <= MAX_DESCRIPTION_CHARS) out[key] = text;
      }
    } else if (SCALAR_SCHEMA_KEYS.has(key)) {
      out[key] = value;
    }
    // Everything else — `example`, `examples`, vendor extensions — is dropped.
  }
  return out;
}

/** Property names are data, so only the values run through the key allowlist. */
function pruneSchemaMap(node: unknown): unknown {
  if (!isRecord(node)) return pruneSchema(node);
  const out: Record<string, unknown> = {};
  for (const [name, schema] of Object.entries(node)) out[name] = pruneSchema(schema);
  return out;
}

function paramSchemasOf(raw: RawOperation): ParamSchema[] {
  const params: ParamSchema[] = [];
  for (const where of ['path', 'query'] as const) {
    for (const parameter of parametersOf(raw, where)) {
      const row: ParamSchema = { name: parameter.name ?? '', in: where };
      if (parameter.required === true) row.required = true;
      const description = stripMarkdown(parameter.description ?? '');
      if (description.length > 0) row.description = truncate(description, MAX_DESCRIPTION_CHARS);
      if (parameter.schema !== undefined) {
        row.schema = pruneSchema(dereference(parameter.schema, raw.spec, new Set()));
      }
      params.push(row);
    }
  }
  return params;
}

/**
 * What `describe_operation` renders. Parameters and body live here rather than
 * on `CatalogOperation` because inlining them into every search result would
 * blow the context budget the catalog exists to protect: search shows the row,
 * describe shows the shape.
 */
function buildSchemas(kept: readonly RawOperation[]): Record<string, OperationSchema> {
  const schemas: Record<string, OperationSchema> = {};
  for (const raw of kept) {
    const entry: OperationSchema = {};
    const params = paramSchemasOf(raw);
    if (params.length > 0) entry.params = params;
    const body = bodySchemaOf(raw);
    if (body !== undefined) entry.body = pruneSchema(dereference(body, raw.spec, new Set()));
    if (entry.params !== undefined || entry.body !== undefined) schemas[raw.id] = entry;
  }
  return schemas;
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Column budget for keeping an array on one line. Matches prettier's default. */
const INLINE_WIDTH = 72;

function renderString(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');
  return `'${escaped}'`;
}

/**
 * Objects always expand and arrays collapse when they fit. That is prettier's
 * own shape, and it happens to be the readable choice: one field per line diffs
 * cleanly, while `pathParams: ['id']` on its own three lines would not.
 */
function renderValue(value: unknown, indent: string): string {
  if (typeof value === 'string') return renderString(value);
  if (typeof value === 'number' || typeof value === 'boolean' || value === null) {
    return String(value);
  }

  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const parts = value.map((item) => renderValue(item, inner));
    const inline = `[${parts.join(', ')}]`;
    if (!inline.includes('\n') && indent.length + inline.length <= INLINE_WIDTH) return inline;
    return `[\n${parts.map((part) => `${inner}${part},`).join('\n')}\n${indent}]`;
  }

  if (isRecord(value)) {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    if (entries.length === 0) return '{}';
    const lines = entries.map(([key, v]) => {
      const renderedKey = IDENTIFIER.test(key) ? key : renderString(key);
      return `${inner}${renderedKey}: ${renderValue(v, inner)},`;
    });
    return `{\n${lines.join('\n')}\n${indent}}`;
  }

  return 'null';
}

function renderCatalog(rows: readonly CatalogOperation[]): string {
  return [
    BANNER,
    "import type { CatalogOperation } from '../types.js';",
    '',
    `export const CATALOG: CatalogOperation[] = ${renderValue(rows, '')};`,
    '',
  ].join('\n');
}

function renderSchemas(schemas: Record<string, OperationSchema>): string {
  return [
    BANNER,
    '/** A path or query parameter, as `describe_operation` renders it. */',
    'export interface ParamSchema {',
    '  name: string;',
    "  in: 'path' | 'query';",
    '  required?: boolean;',
    '  description?: string;',
    '  schema?: unknown;',
    '}',
    '',
    '/**',
    ' * Dereferenced, pruned parameter and request-body schemas for one operation.',
    ' * `body` is absent exactly when the operation takes no JSON body.',
    ' */',
    'export interface OperationSchema {',
    '  params?: ParamSchema[];',
    '  body?: unknown;',
    '}',
    '',
    '/** Keyed by operation id. An absent id takes neither parameters nor a body. */',
    `export const SCHEMAS: Record<string, OperationSchema> = ${renderValue(schemas, '')};`,
    '',
  ].join('\n');
}

function renderMeta(meta: CatalogMeta): string {
  return [
    BANNER,
    "import type { CatalogMeta } from '../types.js';",
    '',
    `export const METADATA: CatalogMeta = ${renderValue(meta, '')};`,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Deterministic timestamp
// ---------------------------------------------------------------------------

const GENERATED_AT_PLACEHOLDER = '__GENERATED_AT__';

function readIfExists(path: string): string | undefined {
  return existsSync(path) ? readFileSync(path, 'utf8') : undefined;
}

/** Git may have handed us CRLF on checkout; that is not a content change. */
function sameContent(a: string | undefined, b: string): boolean {
  return a !== undefined && a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');
}

/**
 * `generatedAt` would otherwise dirty the tree on every run, and CI runs
 * `npm run codegen && git diff --exit-code src/generated`. So the stamp only
 * moves when the emitted content moves: re-running against unchanged specs is a
 * no-op.
 */
function resolveGeneratedAt(previousMeta: string | undefined, template: string): string {
  const now = new Date().toISOString();
  if (previousMeta === undefined) return now;
  const previousStamp = /generatedAt: '([^']*)'/.exec(previousMeta)?.[1];
  if (previousStamp === undefined) return now;
  const replayed = template.replace(
    renderString(GENERATED_AT_PLACEHOLDER),
    renderString(previousStamp),
  );
  return sameContent(previousMeta, replayed) ? previousStamp : now;
}

