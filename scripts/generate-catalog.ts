/**
 * Build-time catalog generator: Hetzner's OpenAPI specs -> src/generated/*.
 *
 * Run with `npm run codegen`. The catalog is committed rather than fetched or
 * parsed at runtime because every MCP client spawns this process fresh: the two
 * vendored specs are ~3.9 MB of JSON, and paying that parse on every stdio
 * start — before the first tool call — is a cost the user notices. CI re-runs
 * this and diffs `src/generated`, so upstream drift breaks the build loudly
 * instead of shipping a stale surface silently.
 *
 * Hetzner is not one API, so this generator reads N specs rather than one. The
 * surface travels with every row from here to the transport; nothing downstream
 * infers it. `robot` has no OpenAPI spec and is deferred, which is why the spec
 * list is a table rather than a pair of variables — adding Robot later is a new
 * entry plus a tag map, not a rewrite.
 */

