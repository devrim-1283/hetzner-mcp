function assertRoutesMatched(
  label: string,
  declared: readonly string[],
  routes: ReadonlyMap<string, number>,
): void {
  const missing = declared.filter((route) => (routes.get(route) ?? 0) !== 1);
  if (missing.length > 0) {
    fail(
      `${label} lists ${missing.length} route(s) that do not match exactly one operation:\n` +
        missing.map((route) => `  ${route} (matched ${routes.get(route) ?? 0})`).join('\n') +
        '\nEither upstream moved them or a spec is wrong. Do not delete the entry to make this ' +
        'pass — find where the operation went first.',
    );
  }
  const duplicated = declared.filter((route, index) => declared.indexOf(route) !== index);
  if (duplicated.length > 0) fail(`${label} lists duplicate routes: ${duplicated.join(', ')}`);
}

/**
 * Ids address operations across every surface at once — the tool layer takes an
 * id, not an (id, surface) pair — so a collision between two specs would make
 * one of the two unreachable, silently and non-deterministically.
 */
function assertIdsUniqueAcrossSurfaces(rows: readonly CatalogOperation[]): void {
  const seen = new Map<string, CatalogOperation>();
  for (const row of rows) {
    const previous = seen.get(row.id);
    if (previous !== undefined) {
      fail(
        `operation id '${row.id}' is used by two surfaces:\n` +
          `  ${previous.surface} ${previous.method} ${previous.path}\n` +
          `  ${row.surface} ${row.method} ${row.path}\n` +
          'Ids must be unique across surfaces because the tool layer addresses operations by id ' +
          'alone. Qualify one of them before regenerating.',
      );
    }
    seen.set(row.id, row);
  }
}

function assertCatalogInvariants(rows: readonly CatalogOperation[]): void {
  if (rows.length === 0) fail('catalog is empty');
  assertIdsUniqueAcrossSurfaces(rows);

  for (const row of rows) {
    if (row.danger === 'safe' && row.method !== 'GET') {
      fail(`${row.id} is classified safe but is a ${row.method}`);
    }
    if (row.danger !== 'safe' && row.method === 'GET') {
      fail(`${row.id} is a GET but is classified ${row.danger}`);
    }
    if (row.method === 'DELETE' && row.danger !== 'destructive') {
      fail(`${row.id} is a DELETE but is classified ${row.danger}`);
    }
    if (row.hasBody && row.method === 'GET') fail(`${row.id} is a GET that declares a body`);
    if (row.costly === true && row.method === 'GET') {
      fail(`${row.id} is a GET flagged costly — reading something cannot open a bill`);
    }
    if (row.summary.trim().length === 0) fail(`${row.id} has no summary`);
    const declared = [...row.pathParams].sort().join(',');
    const actual = pathParamsOf(row.path).sort().join(',');
    if (declared !== actual) fail(`${row.id} pathParams (${declared}) do not match its template`);
  }
}

function assertSchemaCoverage(
  rows: readonly CatalogOperation[],
  schemas: Record<string, OperationSchema>,
): void {
  const withBody = new Set(rows.filter((r) => r.hasBody).map((r) => r.id));
  const withBodySchema = new Set(
    Object.entries(schemas)
      .filter(([, entry]) => entry.body !== undefined)
      .map(([id]) => id),
  );
  const missing = [...withBody].filter((id) => !withBodySchema.has(id));
  const extra = [...withBodySchema].filter((id) => !withBody.has(id));
  if (missing.length > 0) fail(`hasBody without a body schema: ${missing.join(', ')}`);
  if (extra.length > 0) fail(`body schema without hasBody: ${extra.join(', ')}`);

  const ids = new Set(rows.map((r) => r.id));
  const orphans = Object.keys(schemas).filter((id) => !ids.has(id));
  if (orphans.length > 0) fail(`schema without a catalog row: ${orphans.join(', ')}`);
}

/**
 * The pagination and Action probes are the two derivations with no independent
 * witness — nothing downstream would fail loudly if they started returning
 * `false` for everything. So they are pinned to a count and to a known-true
 * example rather than trusted.
 */
function assertProbesStillWork(rows: readonly CatalogOperation[]): void {
  const paginatedCloudGets = rows.filter(
    (r) => r.surface === 'cloud' && r.method === 'GET' && r.paginated === true,
  ).length;
  if (paginatedCloudGets !== EXPECTED_PAGINATED_CLOUD_GETS) {
    fail(
      `expected ${EXPECTED_PAGINATED_CLOUD_GETS} paginated cloud GETs, found ${paginatedCloudGets}.\n` +
        'Either upstream changed its pagination parameters or the detector broke. Check which ' +
        'before touching EXPECTED_PAGINATED_CLOUD_GETS.',
    );
  }

  // `create_server` is the canonical asynchronous mutation: it returns
  // `{ server, action, next_actions }` and the server is not usable until the
  // action finishes. If this stops being detected, the probe is broken.
  const createServer = rows.find((r) => r.id === 'create_server');
  if (createServer?.returnsAction !== true) {
    fail('the returnsAction probe no longer detects create_server, which returns an Action.');
  }

  // A pure catalogue read returns no Action. If this starts being detected, the
  // probe has widened into "mentions an action anywhere" and is worthless.
  const listServerTypes = rows.find((r) => r.id === 'list_server_types');
  if (listServerTypes !== undefined && listServerTypes.returnsAction === true) {
    fail('the returnsAction probe now flags list_server_types, which returns no Action.');
  }
}

// ---------------------------------------------------------------------------
// Reporting
// ---------------------------------------------------------------------------

function printTable(title: string, rows: ReadonlyArray<readonly [string, string]>): void {
  if (rows.length === 0) return;
  const width = Math.max(...rows.map(([label]) => label.length));
  const lines = rows.map(([label, value]) => `  ${label.padEnd(width)}  ${value}`);
  process.stdout.write(`\n${title}\n${lines.join('\n')}\n`);
}

function countBy<T extends string>(values: readonly T[]): Array<readonly [string, string]> {
  const counts = new Map<string, number>();
  for (const value of values) counts.set(value, (counts.get(value) ?? 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([key, count]) => [key, String(count)] as const);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main(): void {
  const loaded = SPEC_SOURCES.map(loadSpec);

  const rawOperations: RawOperation[] = [];
  for (const [index, spec] of loaded.entries()) {
    const source = SPEC_SOURCES[index];
    if (source === undefined) fail('spec source table went out of sync with the loaded specs');
    const operations = collectRawOperations(spec);
    if (operations.length !== source.expectedOperations) {
      fail(
        `expected ${source.expectedOperations} operations in scripts/${source.file}, found ` +
          `${operations.length}.\nThe vendored spec changed. Review the diff, then update the ` +
          'pinned count in the same commit — never adjust it to silence this.',
      );
    }
    rawOperations.push(...operations);
  }

  const routeCounts = new Map<string, number>();
  for (const raw of rawOperations)
    routeCounts.set(raw.route, (routeCounts.get(raw.route) ?? 0) + 1);
  assertRoutesMatched('DESTRUCTIVE_OVERRIDE_ROUTES', DESTRUCTIVE_OVERRIDE_ROUTES, routeCounts);
  assertRoutesMatched('COSTLY_ROUTES', COSTLY_ROUTES, routeCounts);

  const overrides = new Set(DESTRUCTIVE_OVERRIDE_ROUTES);
  const costly = new Set(COSTLY_ROUTES);

  // Sorted so the emitted file is a function of the specs alone: `git diff
  // --exit-code src/generated` is only meaningful if key order is stable.
  const ordered = [...rawOperations].sort(
    (a, b) =>
      (SURFACE_ORDER.get(a.surface) ?? 0) - (SURFACE_ORDER.get(b.surface) ?? 0) ||
      a.path.localeCompare(b.path) ||
      METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method) ||
      a.id.localeCompare(b.id),
  );

  const rows = ordered
    .map((raw) => toCatalogOperation(raw, overrides, costly))
    .sort(
      (a, b) =>
        (SURFACE_ORDER.get(a.surface) ?? 0) - (SURFACE_ORDER.get(b.surface) ?? 0) ||
        a.family.localeCompare(b.family) ||
        a.path.localeCompare(b.path) ||
        METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method) ||
        a.id.localeCompare(b.id),
    );

  assertCatalogInvariants(rows);
  assertProbesStillWork(rows);

  const schemas = buildSchemas(ordered);
  assertSchemaCoverage(rows, schemas);

  const catalogSource = renderCatalog(rows);
  const schemasSource = renderSchemas(schemas);
  const metaTemplate = renderMeta({
    specs: loaded.map((spec) => ({
      surface: spec.surface,
      version: spec.version,
      sha256: spec.sha256,
      operationCount: rows.filter((row) => row.surface === spec.surface).length,
    })),
    operationCount: rows.length,
    generatedAt: GENERATED_AT_PLACEHOLDER,
  });

  const catalogPath = join(OUT_DIR, 'catalog.ts');
  const schemasPath = join(OUT_DIR, 'schemas.ts');
  const metaPath = join(OUT_DIR, 'meta.ts');

  const unchangedElsewhere =
    sameContent(readIfExists(catalogPath), catalogSource) &&
    sameContent(readIfExists(schemasPath), schemasSource);
  const generatedAt = unchangedElsewhere
    ? resolveGeneratedAt(readIfExists(metaPath), metaTemplate)
    : new Date().toISOString();
  const metaSource = metaTemplate.replace(
    renderString(GENERATED_AT_PLACEHOLDER),
    renderString(generatedAt),
  );

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(catalogPath, catalogSource, 'utf8');
  writeFileSync(schemasPath, schemasSource, 'utf8');
  writeFileSync(metaPath, metaSource, 'utf8');

  printTable(
    'hetzner-mcp catalog',
    loaded.map(
      (spec) =>
        [
          `${spec.surface} spec`,
          `v${spec.version}  ${spec.sha256.slice(0, 16)}…  ${rows.filter((r) => r.surface === spec.surface).length} ops`,
        ] as const,
    ),
  );
  printTable('totals', [
    ['operations', String(rows.length)],
    ['body schemas', String(rows.filter((r) => r.hasBody).length)],
    ['paginated', String(rows.filter((r) => r.paginated === true).length)],
    ['returns action', String(rows.filter((r) => r.returnsAction === true).length)],
    ['costly', String(rows.filter((r) => r.costly === true).length)],
    ['generated at', generatedAt],
  ]);
  printTable('by danger', countBy(rows.map((r) => r.danger)));
  printTable('by method', countBy(rows.map((r) => r.method)));
  printTable('by family', countBy(rows.map((r) => r.family)));
  printTable(
    'destructive but not DELETE',
    rows
      .filter((r) => r.danger === 'destructive' && r.method !== 'DELETE')
      .map((r) => [r.id, `${r.surface} ${r.method} ${r.path}`] as const),
  );
  process.stdout.write(`\nwrote ${catalogPath}\n      ${schemasPath}\n      ${metaPath}\n\n`);
}

main();
