/**
 * Hand-maintained. These are not DELETEs, so "gate the DELETEs" misses them,
 * yet each one destroys data that the API cannot give back.
 *
 * Keyed by `surface METHOD /path` rather than by operationId: the route is the
 * semantic identity, while the id is generated by upstream tooling and can be
 * renamed. The surface is part of the key because two surfaces may legitimately
 * serve the same path — `/storage_boxes/...` is account-scoped today, and Robot
 * has its own storage box routes waiting behind the deferred surface.
 *
 * Every entry must match exactly one operation or the generator fails. That
 * tripwire is the entire point: a renamed upstream route must not silently
 * downgrade a destructive operation to an ordinary write.
 */
const DESTRUCTIVE_OVERRIDE_ROUTES: readonly string[] = [
  // "Rebuilds a Server overwriting its disk with the content of an Image,
  // thereby destroying all data on the target Server."
  'cloud POST /servers/{id}/actions/rebuild',

  // "Imports a zone file, replacing all resource record sets." Every RRSet in
  // the zone is replaced in one call; the previous records are not retrievable.
  'cloud POST /zones/{id_or_name}/actions/import_zonefile',

  // "Overwrites the resource records (RRs) of an existing RRSet." The
  // record-level twin of import_zonefile, by the same mechanism. Gating it
  // costs nothing operationally because add_records, remove_records and
  // update_records remain available as ordinary writes for real edits — this
  // is specifically the blind replace-everything verb.
  'cloud POST /zones/{id_or_name}/rrsets/{rr_name}/{rr_type}/actions/set_records',

  // "This will remove all newer Storage Box Snapshots and irrevocably delete
  // all data that was since written to the Storage Box."
  'hetzner POST /storage_boxes/{id}/actions/rollback_snapshot',
];

/**
 * Deliberately NOT overridden, recorded here because each was considered and
 * each will look like an omission to the next reader:
 *
 *  - `POST /firewalls/{id}/actions/set_rules` overwrites all rules, but it is
 *    the ONLY verb for editing them — there is no add_rule — so gating it would
 *    remove firewall editing rather than protect it. The rules are also fully
 *    readable beforehand and re-appliable, which is not true of a wiped disk.
 *  - `POST /servers/{id}/actions/reset` and `poweroff` document that they "may
 *    lead to data loss" by cutting power. They risk unflushed writes; they do
 *    not destroy data by design, and they are the standard recovery verbs for a
 *    hung machine. Gating recovery behind the destructive flag inverts the
 *    purpose of the flag.
 *  - `POST /servers/{id}/actions/change_type` copies the disk to a new machine
 *    and is one-way once `upgrade_disk` is true, but it destroys nothing. It is
 *    costly, not destructive.
 */

