// ---------------------------------------------------------------------------
// Minimal spec shape — only the parts this generator reads
// ---------------------------------------------------------------------------

interface OpenApiParameter {
  name?: string;
  in?: string;
  required?: boolean;
  description?: string;
  schema?: unknown;
}

interface OpenApiOperation {
  operationId?: string;
  summary?: string;
  description?: string;
  tags?: string[];
  parameters?: OpenApiParameter[];
  requestBody?: { content?: Record<string, { schema?: unknown } | undefined> };
  responses?: Record<string, unknown>;
}

interface OpenApiSpec {
  info?: { version?: string };
  paths?: Record<string, Record<string, OpenApiOperation> | undefined>;
  components?: Record<string, unknown>;
}

interface LoadedSpec {
  surface: Surface;
  file: string;
  spec: OpenApiSpec;
  version: string;
  sha256: string;
}

interface RawOperation {
  id: string;
  surface: Surface;
  method: HttpMethod;
  path: string;
  /** `surface METHOD /path` — the key the override lists are written against. */
  route: string;
  op: OpenApiOperation;
  spec: OpenApiSpec;
}

/** Emitted per operation for `describe_operation` to render. */
interface ParamSchema {
  name: string;
  in: 'path' | 'query';
  required?: boolean;
  description?: string;
  schema?: unknown;
}

interface OperationSchema {
  params?: ParamSchema[];
  body?: unknown;
}

function fail(message: string): never {
  process.stderr.write(`\ncodegen FAILED: ${message}\n\n`);
  process.exit(1);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

// ---------------------------------------------------------------------------
// Loading
// ---------------------------------------------------------------------------

/**
 * Line endings are normalised before hashing. `.gitattributes` is supposed to
 * keep the vendored specs byte-identical across platforms, but the hash is the
 * thing CI compares — it should not be able to disagree between a Windows and a
 * Linux checkout because of a checkout rule that lives in a different file.
 */
function sha256Of(source: string): string {
  return createHash('sha256').update(source.replace(/\r\n/g, '\n')).digest('hex');
}

function loadSpec(source: SpecSource): LoadedSpec {
  const path = join(SCRIPT_DIR, source.file);
  if (!existsSync(path)) fail(`vendored spec is missing: scripts/${source.file}`);
  const text = readFileSync(path, 'utf8');
  const spec = JSON.parse(text) as OpenApiSpec;
  const version = spec.info?.version?.trim();
  if (!version) fail(`scripts/${source.file} has no info.version`);
  return { surface: source.surface, file: source.file, spec, version, sha256: sha256Of(text) };
}

function collectRawOperations(loaded: LoadedSpec): RawOperation[] {
  const collected: RawOperation[] = [];
  for (const [path, item] of Object.entries(loaded.spec.paths ?? {})) {
    for (const [verb, op] of Object.entries(item ?? {})) {
      const method = METHOD_ORDER.find((m) => m === verb.toUpperCase());
      if (method === undefined) continue;
      const id = op.operationId?.trim();
      if (!id) {
        fail(
          `${loaded.surface} ${verb.toUpperCase()} ${path} has no operationId — it cannot be addressed.`,
        );
      }
      collected.push({
        id,
        surface: loaded.surface,
        method,
        path,
        route: `${loaded.surface} ${method} ${path}`,
        op,
        spec: loaded.spec,
      });
    }
  }
  return collected;
}

// ---------------------------------------------------------------------------
// Text
// ---------------------------------------------------------------------------

/**
 * Hetzner writes its prose as Markdown: `[Zone](#tag/zones)`. The link target is
 * an anchor inside Hetzner's own docs site and means nothing here, but the label
 * is the noun a user would type, so the label survives and the syntax does not.
 */
function stripMarkdown(text: string): string {
  return text
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*_]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function firstSentence(text: string): string {
  const match = /^[\s\S]*?[.!?](?=\s|$)/.exec(text.trim());
  return (match?.[0] ?? text).trim();
}

function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1).trimEnd()}…`;
}

/**
 * Unlike Coolify's spec, Hetzner's `summary` is a written sentence — "Create a
 * Server", "Change reverse DNS entry for this Server" — and is the better search
 * text. `description` is a page of Markdown including error tables, so it is
 * only the fallback and only its first sentence.
 */
function summaryFor(raw: RawOperation): string {
  const summary = stripMarkdown(raw.op.summary ?? '');
  const description = firstSentence(stripMarkdown(raw.op.description ?? ''));
  return truncate(summary || description || raw.id, MAX_SUMMARY_CHARS);
}

// ---------------------------------------------------------------------------
// $ref resolution
// ---------------------------------------------------------------------------

function resolveRef(spec: OpenApiSpec, ref: string): unknown {
  if (!ref.startsWith('#/')) fail(`external $ref is not supported: ${ref}`);
  let node: unknown = spec;
  for (const segment of ref.slice(2).split('/')) {
    if (!isRecord(node)) fail(`unresolvable $ref: ${ref}`);
    node = node[segment.replace(/~1/g, '/').replace(/~0/g, '~')];
  }
  if (node === undefined) fail(`unresolvable $ref: ${ref}`);
  return node;
}

function dereference(node: unknown, spec: OpenApiSpec, seen: ReadonlySet<string>): unknown {
  if (Array.isArray(node)) return node.map((child) => dereference(child, spec, seen));
  if (!isRecord(node)) return node;

  const ref = node['$ref'];
  if (typeof ref === 'string') {
    // A self-referential schema cannot be inlined. `type: object` is a truthful
    // stand-in: the generic execute path passes bodies through without
    // validating them, so the model loses detail here, never correctness.
    if (seen.has(ref)) return { type: 'object' };
    return dereference(resolveRef(spec, ref), spec, new Set([...seen, ref]));
  }

  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) out[key] = dereference(value, spec, seen);
  return out;
}

/** One level of `$ref`, for probes that must not inline a whole subtree. */
function shallowResolve(node: unknown, spec: OpenApiSpec, seen: ReadonlySet<string>): unknown {
  if (!isRecord(node)) return node;
  const ref = node['$ref'];
  if (typeof ref !== 'string' || seen.has(ref)) return node;
  return shallowResolve(resolveRef(spec, ref), spec, new Set([...seen, ref]));
}

// ---------------------------------------------------------------------------
// Classification
// ---------------------------------------------------------------------------

function classifyDanger(raw: RawOperation, overrides: ReadonlySet<string>): DangerClass {
  if (raw.method === 'DELETE' || overrides.has(raw.route)) return 'destructive';
  if (raw.method === 'GET') return 'safe';
  return 'write';
}

function familyFor(raw: RawOperation): OperationFamily {
  const tags = raw.op.tags ?? [];
  const tag = tags[0];
  if (tag === undefined) {
    fail(`${raw.route} carries no OpenAPI tag, so it cannot be filed into a family.`);
  }
  const byTag = FAMILY_BY_TAG[raw.surface];
  if (byTag === undefined) {
    fail(
      `no FAMILY_BY_TAG entry for surface '${raw.surface}' — add one before vendoring its spec.`,
    );
  }
  const family = byTag[tag];
  if (family === undefined) {
    fail(
      `unmapped ${raw.surface} tag '${tag}' (${raw.route}).\n` +
        'Add it to FAMILY_BY_TAG. Do not fall back to `other` — `other` is for operations that ' +
        'genuinely have no home, not for a tag nobody has looked at yet.',
    );
  }
  return family;
}

function pathParamsOf(path: string): string[] {
  return [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1] ?? '');
}

function parametersOf(raw: RawOperation, where: 'path' | 'query'): OpenApiParameter[] {
  return (raw.op.parameters ?? []).filter(
    (p) => p.in === where && typeof p.name === 'string' && p.name.length > 0,
  );
}

function queryParamsOf(raw: RawOperation): string[] {
  return parametersOf(raw, 'query').map((p) => p.name ?? '');
}

function isPaginated(raw: RawOperation): boolean {
  return queryParamsOf(raw).some((name) => PAGINATION_PARAMS.has(name));
}

function bodySchemaOf(raw: RawOperation): unknown {
  return raw.op.requestBody?.content?.['application/json']?.schema;
}

/**
 * Top-level property names of a schema, following composition keywords only.
 * Deliberately not a deep walk — see ACTION_PROBE_DEPTH.
 */
function envelopeProperties(
  schema: unknown,
  spec: OpenApiSpec,
  depth: number,
  out: Set<string>,
): void {
  if (depth > ACTION_PROBE_DEPTH) return;
  const node = shallowResolve(schema, spec, new Set());
  if (!isRecord(node)) return;

  const properties = node['properties'];
  if (isRecord(properties)) for (const name of Object.keys(properties)) out.add(name);

  for (const key of ['allOf', 'oneOf', 'anyOf']) {
    const branches = node[key];
    if (!Array.isArray(branches)) continue;
    for (const branch of branches) envelopeProperties(branch, spec, depth + 1, out);
  }
}

/**
 * Hetzner mutations are asynchronous: the call returns `{ action: { status:
 * 'running' } }` and the work finishes later. A tool that returns that and stops
 * has told the model nothing about whether anything happened, so the tool layer
 * needs to know which operations behave this way — from the spec, because 144 of
 * 221 do and a hand-list would rot.
 */
function returnsAction(raw: RawOperation): boolean {
  const responses = raw.op.responses ?? {};
  for (const [code, response] of Object.entries(responses)) {
    if (!/^2\d\d$/.test(code)) continue;
    const resolved = shallowResolve(response, raw.spec, new Set());
    if (!isRecord(resolved)) continue;
    const content = resolved['content'];
    if (!isRecord(content)) continue;
    const json = content['application/json'];
    if (!isRecord(json)) continue;

    const properties = new Set<string>();
    envelopeProperties(json['schema'], raw.spec, 0, properties);
    for (const name of properties) if (ACTION_RESPONSE_PROPERTIES.has(name)) return true;
  }
  return false;
}

function toCatalogOperation(
  raw: RawOperation,
  overrides: ReadonlySet<string>,
  costly: ReadonlySet<string>,
): CatalogOperation {
  const row: CatalogOperation = {
    id: raw.id,
    surface: raw.surface,
    method: raw.method,
    path: raw.path,
    family: familyFor(raw),
    summary: summaryFor(raw),
    // Taken from the URL template, not from `parameters`: the template is what
    // the HTTP client must actually substitute, and specs under-declare.
    pathParams: pathParamsOf(raw.path),
    queryParams: queryParamsOf(raw),
    // Derived from the same lookup that emits the schema, so `hasBody === true`
    // and "getSchema(id).body exists" can never disagree.
    hasBody: bodySchemaOf(raw) !== undefined,
    danger: classifyDanger(raw, overrides),
  };
  if (costly.has(raw.route)) row.costly = true;
  if (returnsAction(raw)) row.returnsAction = true;
  if (isPaginated(raw)) row.paginated = true;
  return row;
}

